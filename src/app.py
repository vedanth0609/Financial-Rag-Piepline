@app.post("/api/v1/query", response_model=QueryResponse)
async def query_endpoint(request: QueryRequest):
    """
    Query endpoint that accepts user prompt and returns structured response.
    
    Uses asynchronous hooks (aquery) to prevent thread-blocking.
    Includes safety gate for LLM generation to prevent quota exhaustion.
    """
    try:
        # Initialize query engine if not already initialized
        if not query_engine_manager._initialized:
            query_engine_manager.initialize()
        
        # Process query asynchronously
        response = await query_engine_manager.query(
            query_text=request.query,
            top_k=request.top_k
        )
        
        return response
        
    except HTTPException:
        raise
    except Exception as e:
        console.print(f"[red]✗[/red] Unexpected error in query endpoint: {str(e)}")
        raise HTTPException(status_code=500, detail=f"Internal server error: {str(e)}")


